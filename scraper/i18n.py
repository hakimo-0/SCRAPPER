def translate(text: str, language: str = DEFAULT_LANGUAGE) -> str:
    """Translate a German UI string; unknown strings remain visible in German."""
    if language not in LANGUAGES:
        language = DEFAULT_LANGUAGE
    return _TRANSLATIONS.get(language, {}).get(text, text)


def is_rtl(language: str) -> bool:
    return language == "العربية"


